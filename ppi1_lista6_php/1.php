    <h1>Quais são as tags usadas para definição de código PHP?</h1>
    <p>Tag padrão <?php e ?> : É a forma oficial, recomendada e universalmente aceita para iniciar e encerrar códigos PHP.</p>

    • Tag curta de impressão (<?=): Funciona como um atalho para <?php echo. Ela é sempre suportada a partir do PHP 5.4.0 e dispensa o uso de echo.
• Tags curtas tradicionais (<? e ?>): Permitem abrir o código apenas com <?. Porém, dependem da diretiva short_open_tag estar ativada no arquivo php.ini e podem gerar conflito com documentos XML, por isso o uso é desencorajado

